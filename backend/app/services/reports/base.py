"""Base report class with CSV/XLSX formula injection protection and export formatters."""

from __future__ import annotations

import csv
import io
from abc import ABC, abstractmethod
from datetime import datetime
from typing import Any, AsyncIterator

import openpyxl
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from sqlalchemy.ext.asyncio import AsyncSession

from app.core import clock
from app.db.models.user import User


def sanitize_cell_value(val: Any) -> Any:
    """Protect against CSV/XLSX formula injection.

    Prefix values beginning with =, +, -, or @ with an apostrophe.
    """
    if isinstance(val, str) and val and val[0] in ("=", "+", "-", "@"):
        return f"'{val}"
    return val


class BaseReport(ABC):
    """Abstract base class for all tabular and printable reports."""

    slug: str
    title: str
    description: str
    supported_formats: list[str] = ["json", "csv", "xlsx"]

    @abstractmethod
    async def fetch_data(
        self,
        session: AsyncSession,
        user: User,
        params: dict[str, Any],
        max_rows: int,
    ) -> tuple[list[dict[str, Any]], list[str], bool]:
        """Fetch report records.

        Returns (rows: list[dict], field_names: list[str], is_truncated: bool).
        """
        raise NotImplementedError

    @classmethod
    def to_csv_stream(cls, rows: list[dict[str, Any]], fieldnames: list[str]) -> AsyncIterator[str]:
        """Generate a streaming CSV output with injection sanitization."""
        async def _generator():
            out = io.StringIO()
            writer = csv.DictWriter(out, fieldnames=fieldnames, lineterminator="\n")
            writer.writeheader()
            yield out.getvalue()
            out.seek(0)
            out.truncate(0)

            for row in rows:
                sanitized_row = {k: sanitize_cell_value(v) for k, v in row.items()}
                writer.writerow(sanitized_row)
                yield out.getvalue()
                out.seek(0)
                out.truncate(0)

        return _generator()

    @classmethod
    def to_xlsx(
        cls,
        title: str,
        rows: list[dict[str, Any]],
        fieldnames: list[str],
        user: User,
        params: dict[str, Any],
        is_truncated: bool = False,
    ) -> bytes:
        """Render a professionally formatted Excel workbook with OpenPyXL."""
        wb = openpyxl.Workbook()
        ws_data = wb.active
        ws_data.title = "Report Data"

        # Theme colors
        header_fill = PatternFill(start_color="1B365D", end_color="1B365D", fill_type="solid")
        header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
        thin_border = Border(
            left=Side(style="thin", color="D3D3D3"),
            right=Side(style="thin", color="D3D3D3"),
            top=Side(style="thin", color="D3D3D3"),
            bottom=Side(style="thin", color="D3D3D3"),
        )

        # Write Header
        ws_data.append(fieldnames)
        for col_idx in range(1, len(fieldnames) + 1):
            cell = ws_data.cell(row=1, column=col_idx)
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(horizontal="center", vertical="center")

        ws_data.freeze_panes = "A2"

        # Write Rows with sanitization
        for row in rows:
            row_vals = [sanitize_cell_value(row.get(f, "")) for f in fieldnames]
            ws_data.append(row_vals)

        # Apply borders and formatting
        for row_cells in ws_data.iter_rows(min_row=2, max_row=len(rows) + 1, min_col=1, max_col=len(fieldnames)):
            for cell in row_cells:
                cell.border = thin_border

        if is_truncated:
            ws_data.append([f"NOTE: Data was truncated to maximum export row limit."])

        # Auto-adjust column widths
        for col in ws_data.columns:
            max_len = max(len(str(cell.value or "")) for cell in col)
            col_letter = openpyxl.utils.get_column_letter(col[0].column)
            ws_data.column_dimensions[col_letter].width = min(max(max_len + 3, 12), 40)

        # Metadata Sheet
        ws_meta = wb.create_sheet(title="Report Metadata")
        ws_meta.append(["Report Title", title])
        ws_meta.append(["Generated At", clock.now().strftime("%Y-%m-%d %H:%M:%S IST")])
        ws_meta.append(["Generated By", user.email])
        ws_meta.append(["Role", user.role.value])
        ws_meta.append(["Total Records", len(rows)])
        ws_meta.append(["Filters Applied", str(params)])
        for r in range(1, 7):
            ws_meta.cell(row=r, column=1).font = Font(bold=True)

        buffer = io.BytesIO()
        wb.save(buffer)
        return buffer.getvalue()

    @classmethod
    def to_pdf(
        cls,
        title: str,
        rows: list[dict[str, Any]],
        fieldnames: list[str],
        user: User,
        params: dict[str, Any],
    ) -> bytes:
        """Render a printable summary PDF using ReportLab."""
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=landscape(A4),
            leftMargin=0.5 * inch,
            rightMargin=0.5 * inch,
            topMargin=0.5 * inch,
            bottomMargin=0.5 * inch,
        )

        styles = getSampleStyleSheet()
        story = []

        title_style = ParagraphStyle(
            "PDFTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=colors.HexColor("#1B365D"),
            spaceAfter=6,
        )
        meta_style = ParagraphStyle(
            "PDFMeta",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=colors.dimgrey,
            spaceAfter=12,
        )
        cell_style = ParagraphStyle(
            "PDFCell",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8,
            leading=10,
        )
        header_cell_style = ParagraphStyle(
            "PDFHeaderCell",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8,
            leading=10,
            textColor=colors.white,
        )

        story.append(Paragraph(f"AICTE FDR Portal — {title}", title_style))
        story.append(
            Paragraph(
                f"Generated By: {user.email} ({user.role.value}) | Date: {clock.now().strftime('%d-%b-%Y %H:%M')} | Total: {len(rows)} rows",
                meta_style,
            )
        )

        # Table data
        header_row = [Paragraph(f, header_cell_style) for f in fieldnames]
        table_data = [header_row]

        # Max 200 rows in PDF printable preview
        pdf_rows = rows[:200]
        for r in pdf_rows:
            table_data.append([Paragraph(str(r.get(f, "")), cell_style) for f in fieldnames])

        col_w = (10.69 * inch) / len(fieldnames)
        pdf_table = Table(table_data, colWidths=[col_w] * len(fieldnames))
        pdf_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1B365D")),
                    ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#D3D3D3")),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E5E5")),
                    ("TOPPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )
        story.append(pdf_table)

        if len(rows) > 200:
            story.append(Spacer(1, 10))
            story.append(
                Paragraph(
                    f"Showing top 200 of {len(rows)} rows in PDF preview. Export CSV or XLSX for complete dataset.",
                    meta_style,
                )
            )

        doc.build(story)
        return buffer.getvalue()
